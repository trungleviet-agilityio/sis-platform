"""Generate the rule table in intake/README.md from rules/rules.json.

python3 -m sis_intake.ruletable           print the table
python3 -m sis_intake.ruletable --write   rewrite the table inside README.md
python3 -m sis_intake.ruletable --check   exit 1 when README.md is out of date
"""

from __future__ import annotations

import sys
from pathlib import Path

if __package__ in (None, ""):
    sys.path.insert(0, str(Path(__file__).resolve().parent.parent))

from sis_intake import rules  # noqa: E402

README = Path(__file__).resolve().parent.parent / "README.md"
BEGIN = "<!-- rules:begin (generated by sis_intake/ruletable.py, do not edit) -->"
END = "<!-- rules:end -->"


def render() -> str:
    lines = [
        "| ID | Rule | Sev | Pillars | WA ref |",
        "|---|---|---|---|---|",
    ]
    for rule in rules.load_rules()["rules"]:
        lines.append(
            "| {} | {} | {} | {} | {} |".format(
                rule["id"],
                rule["rule"],
                rule["severity"],
                ", ".join(rule["pillars"]),
                ", ".join(rule["wa_refs"]),
            )
        )
    return "\n".join(lines)


def extract(readme: str) -> str | None:
    """The text between the markers, or None when the markers are missing."""
    start = readme.find(BEGIN)
    stop = readme.find(END)
    if start < 0 or stop < start:
        return None
    return readme[start + len(BEGIN) : stop].strip("\n")


def main(argv: list[str]) -> int:
    table = render()
    text = README.read_text(encoding="utf-8")
    if "--write" in argv:
        start = text.index(BEGIN) + len(BEGIN)
        stop = text.index(END)
        README.write_text(text[:start] + "\n" + table + "\n" + text[stop:], encoding="utf-8")
        return 0
    if "--check" in argv:
        if extract(text) == table:
            return 0
        sys.stderr.write(
            "intake/README.md rule table is out of date: "
            "run python3 -m sis_intake.ruletable --write\n"
        )
        return 1
    sys.stdout.write(table + "\n")
    return 0


if __name__ == "__main__":
    sys.exit(main(sys.argv[1:]))
